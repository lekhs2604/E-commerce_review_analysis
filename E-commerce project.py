"""NAME ENTITY RECOGNITION WITH SPACY"""

def extract_entities(text):
  ''' return list of (entity_text,entity_label) tuples.'''
  doc=nlp(text)
  return[(ent.text,ent.label_)for ent in doc.ents]
def get_noun_phrases(text):
  '''extract multi-word noun phrases using spacy dependency parser.'''
  doc=nlp(text)
  return[chunk.text.lower() for chunk in doc.noun_chunks
         if len(chunk.text.split())>1]
df['entities']=df['review_text'].apply(extract_entities)
df['noun_phrases']=df['review_text'].apply(get_noun_phrases)
