"""CUSTOMER SEGMENTAION USING K-MEANS CLUSTER"""

cluster_feats=['num_orders','total_spend','num_returns','rating','compound_score']
X_c=df[cluster_feats].copy()
scaler_c=StandardScaler()
X_scaled=scaler_c.fit_transform(X_c)
inertias=[]
silhouettes=[]
K_range=range(2,11)
for k in K_range:
  km=KMeans(n_clusters=k,random_state=42,n_init=15,max_iter=300)
  labels=km.fit_predict(X_scaled)
  inertias.append(km.inertia_)
  silhouettes.append(silhouette_score(X_scaled,labels))
fig,(ax1,ax2)=plt.subplots(1,2,figsize=(13,5))
ax1.plot(list(K_range),inertias, 'bo-', linewidth=2, markersize=8)
ax1.set(title='Elbow Method — Inertia vs K',
xlabel='Number of Clusters (K)', ylabel='Inertia (WCSS)')
ax1.grid(True, alpha=0.3)
ax2.plot(list(K_range), silhouettes, 'rs-', linewidth=2, markersize=8)
ax2.set(title='Silhouette Score vs K',
xlabel='Number of Clusters (K)', ylabel='Silhouette Score')
ax2.grid(True, alpha=0.3)
plt.suptitle('Choosing Optimal K for K-Means', fontsize=13)
plt.tight_layout()

plt.savefig('elbow_silhouette.png', dpi=150, bbox_inches='tight')
plt.show()

