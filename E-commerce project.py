import string
from nltk.corpus import stopwords
from nltk.tokenize import word_tokenize
from nltk.stem import WordNetLemmatizer
import nltk

nltk.download('stopwords', quiet=True)
nltk.download('wordnet', quiet=True)
nltk.download('punkt', quiet=True)
nltk.download('punkt_tab', quiet=True)

stop_words=set(stopwords.words('english'))
lemmatizer=WordNetLemmatizer()
def preprocessor_text(text):
  ''' Pipeline:lowercase → remove punctuation → tokenise →
      remove stop-words → lemmatise → rejoin
  '''
  text=text.lower()
  text=text.translate(str.maketrans('','',string.punctuation))
  tokens=word_tokenize(text)
  tokens=[t for t in tokens if t not in stop_words and t.isalpha()]
  tokens=[lemmatizer.lemmatize(t) for t in tokens]
  return ''.join(tokens)
df['clean_review']=df['review_text'].apply(preprocessor_text)
print(df[['review_text','clean_review']].head(4).to_string())

"""SENTIMENT ANALYZER USING VADER"""

sia=SentimentIntensityAnalyzer()
def classify_sentiment(text):
  scores=sia.polarity_scores(text)
  compound=scores['compound']
  if compound>=0.05:
    return 'Positive'
  elif compound<=-0.05:
    return 'Negative'
  else:
    return 'Netural'
df['compound_score']=df['review_text'].apply(
    lambda x:sia.polarity_scores(x)['compound'])
df['sentiment']=df['review_text'].apply(classify_sentiment)
print('Sentiment Distribution:')
print(df['sentiment'].value_counts())
